// Map Link: paste a Google Maps link (e.g. https://maps.app.goo.gl/...) and
// GET /api/places/from-link reads its pin, place name and address; onPlace
// moves the map pin and fills the form. Only typing or pasting here looks the
// link up; the link the map writes back after a drag is not looked up again.
function MapLinkField({ value, onChange, onPlace }) {
  const [status, setStatus] = useState({ kind: "", text: "" });
  const timer = useRef(null);
  const seq = useRef(0);

  useEffect(() => () => clearTimeout(timer.current), []);

  const resolve = async (url) => {
    const id = ++seq.current;
    setStatus({ kind: "loading", text: "Reading the link…" });
    try {
      const res = await fetch(`${API_BASE}/places/from-link?url=${encodeURIComponent(url)}`, { headers: authHeaders() });
      const data = await res.json().catch(() => null);
      if (id !== seq.current) return;
      if (!res.ok) { setStatus({ kind: "error", text: data?.message || "Couldn't read that link." }); return; }
      onPlace(data);
      setStatus({ kind: "ok", text: `Pin set${data.name ? `: ${data.name}` : data.label ? `: ${data.label}` : ""}` });
    } catch {
      if (id === seq.current) setStatus({ kind: "error", text: "Couldn't read that link. Check the connection." });
    }
  };

  const typed = (v) => {
    onChange(v);
    clearTimeout(timer.current);
    const url = v.trim();
    if (!url) { seq.current++; setStatus({ kind: "", text: "" }); return; }
    if (!/goo\.gl|google\./i.test(url)) { setStatus({ kind: "error", text: "Paste a Google Maps link, e.g. https://maps.app.goo.gl/..." }); return; }
    timer.current = setTimeout(() => resolve(url), 500);
  };

  return (
    <div>
      <label className="text-[11px] text-slate-500 mb-1 block">Map Link</label>
      <input
        type="url"
        value={value}
        onChange={(e) => typed(e.target.value)}
        placeholder="Paste the Google Maps link, e.g. https://maps.app.goo.gl/..."
        autoComplete="off"
        className="w-full bg-slate-50 border border-black/[0.09] rounded-md px-2.5 py-1.5 text-[13px] outline-none focus:border-cyan-500"
      />
      <div className={`mt-1 text-[11px] ${status.kind === "error" ? "text-red-600" : status.kind === "ok" ? "text-emerald-600" : "text-slate-400"}`}>
        {status.text || "In Google Maps, open the store, click Share, then copy the link here."}
      </div>
    </div>
  );
}

const EMAIL_DOMAIN = "atice.cloud";

// Full address with the company domain, or null when there is nothing to
// suggest. "juan" and "juan@at" both suggest "juan@atice.cloud"; an address
// on another domain ("juan@gmail.com") is left alone.
function suggestEmail(value) {
  const v = value.trim();
  if (!v) return null;
  const at = v.indexOf("@");
  if (at === -1) return `${v}@${EMAIL_DOMAIN}`;
  const local = v.slice(0, at);
  const domain = v.slice(at + 1).toLowerCase();
  if (!local || domain === EMAIL_DOMAIN || !EMAIL_DOMAIN.startsWith(domain)) return null;
  return `${local}@${EMAIL_DOMAIN}`;
}

// Email input that offers the @atice.cloud domain while typing. The
// suggestion is used on Tab, on a click, or when the field loses focus.
// When the field loses focus, GET /customers/check-email says whether the
// email account exists, so a typo shows before saving (the server refuses a
// non-existing account when saving too). `savedEmail` is not checked again.
function EmailDomainField({ label, value, onChange, required, savedEmail = "" }) {
  const suggestion = suggestEmail(value);
  const [check, setCheck] = useState({ email: "", result: "" });
  const seq = useRef(0);

  const verify = async (email) => {
    const v = email.trim().toLowerCase();
    if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(v) || v === savedEmail.trim().toLowerCase()) { setCheck({ email: "", result: "" }); return; }
    const id = ++seq.current;
    setCheck({ email: v, result: "checking" });
    try {
      const res = await fetch(`${API_BASE}/customers/check-email?email=${encodeURIComponent(v)}`, { headers: authHeaders() });
      const data = await res.json().catch(() => null);
      if (id === seq.current) setCheck({ email: v, result: res.ok ? data?.result || "unknown" : "unknown" });
    } catch {
      if (id === seq.current) setCheck({ email: v, result: "unknown" });
    }
  };
  const accept = () => {
    if (suggestion) onChange(suggestion);
    verify(suggestion || value);
  };
  const shown = check.email && check.email === value.trim().toLowerCase() ? check.result : "";

  return (
    <div>
      <label className="text-[11px] text-slate-500 mb-1 block">{label}</label>
      <input
        type="email"
        value={value}
        onChange={(e) => onChange(e.target.value)}
        onBlur={accept}
        onKeyDown={(e) => {
          if (e.key === "Tab" && suggestion) accept();
        }}
        required={required}
        placeholder={`name@${EMAIL_DOMAIN}`}
        autoComplete="off"
        className="w-full bg-slate-50 border border-black/[0.09] rounded-md px-2.5 py-1.5 text-[13px] outline-none focus:border-cyan-500"
      />
      {suggestion && (
        <button
          type="button"
          onMouseDown={(e) => e.preventDefault()}
          onClick={accept}
          className="mt-1 text-[11px] text-slate-500 hover:text-cyan-600 cursor-pointer"
        >
          Use <span className="font-medium text-cyan-600">{suggestion}</span> (Tab)
        </button>
      )}
      {shown && (
        <div className={`mt-1 text-[11px] ${shown === "valid" ? "text-emerald-600" : shown === "invalid" ? "text-red-600" : shown === "checking" ? "text-slate-400" : "text-amber-600"}`}>
          {shown === "checking" && "Checking that this email account exists…"}
          {shown === "valid" && "✓ This email account exists."}
          {shown === "invalid" && "✗ This email account does not exist. Check the spelling. The customer can't be saved with it."}
          {shown === "unknown" && "This email's provider doesn't say whether the account exists. Double-check the spelling with the customer."}
        </div>
      )}
    </div>
  );
}

